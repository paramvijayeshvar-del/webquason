function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="en">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const pathname = useLocation({ select: (location) => location.pathname });

  useEffect(() => {
    const targets = document.querySelectorAll<HTMLElement>("main > section, main > div.grid");
    if (!window.IntersectionObserver || window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    const observer = new IntersectionObserver((entries) => {
      entries.forEach((entry) => {
        if (entry.isIntersecting) {
          entry.target.classList.add("reveal-in");
          observer.unobserve(entry.target);
        }
      });
    }, { threshold: 0.08, rootMargin: "0px 0px -30px 0px" });
    targets.forEach((target) => observer.observe(target));
    return () => observer.disconnect();
  }, [pathname]);

  return (
    <QueryClientProvider client={queryClient}>
      <KeepsakeProvider>
      <div className="mx-auto min-h-screen max-w-6xl px-5 pb-28 sm:px-8 sm:pb-0">
        <SiteNav />
        <main key={pathname} className="page-enter">
          <Outlet />
        </main>
        <footer className="mt-14 border-t border-border py-8 text-center">
          <p className="font-hand text-2xl text-ink-soft">made with a little magic, just for you ✦</p>
        </footer>
      </div>
      <DevPanel />
      </KeepsakeProvider>
    </QueryClientProvider>
  );
}
